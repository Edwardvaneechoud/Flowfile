def test_metadata_and_stray_cell_reads_only_the_real_table(tmp_path, caplog):
    """The reported ShapeError case: eight real columns survive a ten-cell used range."""
    path = _metadata_and_stray_cell(tmp_path)
    settings = ExcelSettings(sheet_name=SHEET, start_row=2)
    assert select_excel_engine(settings) == "calamine"

    with caplog.at_level(logging.WARNING, logger="shared.excel_reader"):
        df = read_excel_table(path, settings)

    assert df.columns == [f"h{i}" for i in range(8)]
    assert df.height == 4
    assert "ragged used range" in caplog.text


def test_metadata_and_stray_cell_with_type_inference_keeps_the_used_range(tmp_path):
    """Type inference routes to openpyxl, which reports all ten declared columns without raising."""
    path = _metadata_and_stray_cell(tmp_path)
    settings = ExcelSettings(sheet_name=SHEET, start_row=2, type_inference=True)
    assert select_excel_engine(settings) == "openpyxl"

    df = read_excel_table(path, settings)

    assert df.width == 10
    assert df.columns[:8] == [f"h{i}" for i in range(8)]
    assert df.height == 4


def test_orphan_cell_below_right_does_not_raise(tmp_path, caplog):
    """A value parked outside the table widens the used range but must not fail the read."""
    path = _orphan_cell_below_right(tmp_path)

    with caplog.at_level(logging.WARNING, logger="shared.excel_reader"):
        df = read_excel_table(path, ExcelSettings(sheet_name=SHEET))

    assert df.columns == ["a", "b", "_unnamed_column_2"]
    assert "ragged used range" in caplog.text


def test_stray_cell_on_header_row_keeps_the_names_calamine_found(tmp_path):
    """Truncating openpyxl's header positionally would be wrong here, so calamine's names win.

    The used range is six cells -- ('a', 'b', None, None, None, 'note') -- while calamine drops the
    three empty columns and keeps 'note' as a third column. Taking openpyxl's first three cells
    would name that third column from a blank cell instead of from the value backing it.
    """
    path = _stray_cell_on_header_row(tmp_path)

    df = read_excel_table(path, ExcelSettings(sheet_name=SHEET))

    assert df.columns == ["a", "b", "note"]
    assert df.height == 3


