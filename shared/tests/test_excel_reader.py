SHEET = "Sheet1"


@dataclass
class ExcelSettings:
    """The duck-typed slice of the Read node's excel settings that the reader actually looks at."""

    sheet_name: str = None
    start_row: int = 0
    start_column: int = 0
    end_row: int = 0
    end_column: int = 0
    has_headers: bool = True
    type_inference: bool = False


class Recorder:
    """Stand-in for a run's NodeLogger: the reader accepts anything with .info/.warning."""

    def __init__(self):
        self.info_lines = []
        self.warning_lines = []

    def info(self, message):
        self.info_lines.append(str(message))

    def warning(self, message):
        self.warning_lines.append(str(message))


def _save(tmp_path, name, fill):
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = SHEET
    fill(ws)
    path = tmp_path / name
    wb.save(path)
    return str(path)


def _plain_table(tmp_path, name="plain.xlsx"):
    """A boring A1-anchored table: header row a,b followed by three data rows."""

    def fill(ws):
        ws.cell(row=1, column=1, value="a")
        ws.cell(row=1, column=2, value="b")
        for row in range(2, 5):
            ws.cell(row=row, column=1, value=row)
            ws.cell(row=row, column=2, value=row * 10)

    return _save(tmp_path, name, fill)


def _metadata_and_stray_cell(tmp_path):
    """The reported case: a metadata line above the table plus a stray note off to the right.

    Openpyxl's used range is A1:J7 while the table under the metadata is only eight columns wide.
    """

    def fill(ws):
        ws.cell(row=1, column=1, value="Report generated by Finance")
        ws.cell(row=1, column=10, value="stray note")
        for col in range(1, 9):
            ws.cell(row=3, column=col, value=f"h{col - 1}")
        for row in range(4, 8):
            for col in range(1, 9):
                ws.cell(row=row, column=col, value=(row - 4) * 8 + col)

    return _save(tmp_path, "metadata.xlsx", fill)


def _orphan_cell_below_right(tmp_path):
    """A two-column table with one orphan value parked below and to the right of it."""

    def fill(ws):
        ws.cell(row=1, column=1, value="a")
        ws.cell(row=1, column=2, value="b")
        for row in range(2, 5):
            ws.cell(row=row, column=1, value=row)
            ws.cell(row=row, column=2, value=row * 10)
        ws.cell(row=9, column=6, value="orphan")

    return _save(tmp_path, "orphan.xlsx", fill)


def _stray_cell_on_header_row(tmp_path):
    """A two-column table with a loose note sitting in column F of the header row itself."""

    def fill(ws):
        ws.cell(row=1, column=1, value="a")
        ws.cell(row=1, column=2, value="b")
        ws.cell(row=1, column=6, value="note")
        for row in range(2, 5):
            ws.cell(row=row, column=1, value=row)
            ws.cell(row=row, column=2, value=row * 10)

    return _save(tmp_path, "stray.xlsx", fill)


def _blank_interior_header_cell(tmp_path):
    """Four columns of data whose third header cell was never filled in."""

    def fill(ws):
        for col, value in ((1, "a"), (2, "b"), (4, "d")):
            ws.cell(row=1, column=col, value=value)
        for row in range(2, 5):
            for col in range(1, 5):
                ws.cell(row=row, column=col, value=row * col)

    return _save(tmp_path, "blank_interior.xlsx", fill)


def _leading_blank_header_cell(tmp_path):
    """Three columns of data whose first header cell is blank, as a row-label column often is."""

    def fill(ws):
        ws.cell(row=1, column=2, value="b")
        ws.cell(row=1, column=3, value="c")
        for row in range(2, 5):
            for col in range(1, 4):
                ws.cell(row=row, column=col, value=row * col)

    return _save(tmp_path, "leading_blank.xlsx", fill)


def _datetime_header_row(tmp_path):
    """Issue #356: a title row above a header row whose month columns are real datetimes."""

    def fill(ws):
        for col in range(1, 12):
            ws.cell(row=1, column=col, value=f"title{col}")
        header = ["Ledger"] + [datetime.datetime(2025, month, 1) for month in range(4, 13)] + ["Location"]
        for col, value in enumerate(header, start=1):
            ws.cell(row=2, column=col, value=value)
        for col in range(1, 12):
            ws.cell(row=3, column=col, value=col * 1.5)

    return _save(tmp_path, "datetime_header.xlsx", fill)


def _empty_sheet(tmp_path):
    """A workbook holding one sheet without a single cell in it."""
    return _save(tmp_path, "empty.xlsx", lambda ws: None)


