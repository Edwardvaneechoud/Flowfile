def test_ensure_unique_versions_duplicates():
    # The suffix is the occurrence count, so the second "a" is "a_v2" rather than "a_v1".
    assert ensure_unique(["a", "a", "b", "a"]) == ["a", "a_v2", "b", "a_v3"]
    assert ensure_unique(["a", "a_v2", "a"]) == ["a", "a_v2", "a_v3"]
    assert ensure_unique([]) == []


def test_duplicate_headers_are_made_unique(tmp_path):
    """Two columns sharing a name still produce a constructible frame."""

    def fill(ws):
        ws.cell(row=1, column=1, value="a")
        ws.cell(row=1, column=2, value="a")
        for row in range(2, 4):
            ws.cell(row=row, column=1, value=row)
            ws.cell(row=row, column=2, value=row * 10)

    path = _save(tmp_path, "dupes.xlsx", fill)

    df = read_excel_table(path, ExcelSettings(sheet_name=SHEET))

    assert df.columns == ["a", "a_v2"]
    assert isinstance(df, pl.DataFrame)


def test_ensure_unique_terminates_when_the_versioned_name_already_exists():
    """['a', 'a_v2', 'a'] looped forever: the retry bumped the candidate's counter, not the item's."""
    assert ensure_unique(["a", "a_v2", "a"]) == ["a", "a_v2", "a_v3"]
    assert ensure_unique(["a", "a_v2", "a_v3", "a", "a"]) == ["a", "a_v2", "a_v3", "a_v4", "a_v5"]


def test_reading_a_sheet_whose_headers_collide_with_a_version_suffix(tmp_path):
    """A header row of a, a_v2, a used to hang the reader with no error and no timeout."""
    def fill(ws):
        for column, header in enumerate(["a", "a_v2", "a"], start=1):
            ws.cell(row=1, column=column, value=header)
        for column in range(1, 4):
            ws.cell(row=2, column=column, value=column)

    path = _save(tmp_path, "version_collision.xlsx", fill)

    df = read_excel_table(path, ExcelSettings(sheet_name=SHEET))

    assert df.columns == ["a", "a_v2", "a_v3"]


def _offset_table(tmp_path):
    """The reported layout: three preamble rows, the header on Excel row 4, twenty data rows below it."""

    def fill(ws):
        for _ in range(3):
            ws.append(["preamble", None, None, None])
        ws.append(["id", "name", "qty", "region"])
        for i in range(1, 21):
            ws.append([i, f"item-{i}", i * 3, "north"])

    return _save(tmp_path, "offset.xlsx", fill)


def _headerless_table(tmp_path):
    """Five rows of data anchored at A1 with no header row at all."""

    def fill(ws):
        for i in range(1, 6):
            ws.append([i, f"v{i}"])

    return _save(tmp_path, "headerless.xlsx", fill)


def _normalized(df):
    """Shape plus stringified cells: dtypes and headerless column names vary by engine, the selection must not."""
    return df.shape, [tuple(str(value) for value in row) for row in df.rows()]


RANGE_CASES = [
    pytest.param(ExcelSettings(sheet_name=SHEET, start_row=3, end_row=8), id="rows-3-8"),
    pytest.param(ExcelSettings(sheet_name=SHEET, start_row=3, end_row=8, has_headers=False), id="rows-3-8-headerless"),
    pytest.param(
        ExcelSettings(sheet_name=SHEET, start_row=3, end_row=8, start_column=1, end_column=3), id="rows-3-8-cols-1-3"
    ),
    pytest.param(
        ExcelSettings(sheet_name=SHEET, start_row=3, end_row=8, start_column=1, end_column=3, has_headers=False),
        id="rows-3-8-cols-1-3-headerless",
    ),
    pytest.param(ExcelSettings(sheet_name=SHEET, start_row=3, end_row=4), id="single-data-row"),
    pytest.param(ExcelSettings(sheet_name=SHEET, start_row=3, start_column=1), id="column-offset-without-end"),
    pytest.param(ExcelSettings(sheet_name=SHEET, start_row=3, end_row=99), id="end-row-past-the-sheet"),
]


@pytest.mark.parametrize("engine", ["calamine", "xlsx2csv"])
@pytest.mark.parametrize("settings", RANGE_CASES)
def test_engines_agree_on_row_and_column_selection(tmp_path, engine, settings):
    """Every engine selects the same cells as openpyxl, whose absolute 1-based bounds are unambiguous.

    Toggling 'Type inference' swaps the engine, so any disagreement here means the same range settings
    read a different number of rows depending on a checkbox.
    """
    if engine == "calamine" and not settings.has_headers:
        pytest.skip("df_from_calamine_xlsx always reads the first row of the range as the header")
    path = _offset_table(tmp_path)
    log = logging.getLogger("shared.excel_reader")

    reference = excel_reader._read_with_engine("openpyxl", path, settings, log)
    df = excel_reader._read_with_engine(engine, path, settings, log)

    assert _normalized(df) == _normalized(reference)
    if settings.has_headers:
        assert df.columns == reference.columns


def test_end_row_is_a_zero_based_inclusive_sheet_row(tmp_path):
    """Per the docs, end_row is the zero-based row at which reading stops: end_row=8 keeps Excel row 9."""
    path = _offset_table(tmp_path)

    df = read_excel_table(path, ExcelSettings(sheet_name=SHEET, start_row=3, end_row=8))

    assert df.columns == ["id", "name", "qty", "region"]
    assert df.height == 5
    assert df.row(-1) == (5, "item-5", 15, "north")


def test_type_inference_does_not_change_the_row_count(tmp_path):
    """The reported bug: the same headerless range read 8 rows via xlsx2csv but 6 via openpyxl."""
    path = _offset_table(tmp_path)
    base = ExcelSettings(sheet_name=SHEET, start_row=3, end_row=8, has_headers=False)

    without_inference = read_excel_table(path, base)
    with_inference = read_excel_table(path, replace(base, type_inference=True))

    assert select_excel_engine(base) != select_excel_engine(replace(base, type_inference=True))
    assert without_inference.height == with_inference.height == 6
    assert _normalized(without_inference) == _normalized(with_inference)
    assert tuple(str(value) for value in without_inference.row(-1)) == ("5", "item-5", "15", "north")


