def test_failing_engine_degrades_to_openpyxl(tmp_path, monkeypatch):
    """A broken calamine read is retried with openpyxl, which does not go through pl.read_excel."""
    path = _plain_table(tmp_path)

    def boom(*args, **kwargs):
        raise RuntimeError("calamine exploded")

    monkeypatch.setattr(excel_reader.pl, "read_excel", boom)
    recorder = Recorder()

    df = read_excel_table(path, ExcelSettings(sheet_name=SHEET), logger=recorder)

    assert df.columns == ["a", "b"]
    assert df.height == 3
    warning = "\n".join(recorder.warning_lines)
    assert "calamine" in warning
    assert "Type inference" in warning


def test_failure_on_the_fallback_engine_propagates(tmp_path, monkeypatch):
    """When openpyxl is already the chosen engine there is nothing to degrade to, so it raises."""
